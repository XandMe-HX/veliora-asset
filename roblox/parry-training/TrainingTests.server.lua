-- Put this Script beside the three ModuleScripts in ServerScriptService.
-- Run in a private Roblox Studio place. Tests use synthetic events and a fake clock.
local Resolver=require(script.Parent.CombatResolver)
local passed,failed=0,0
local function test(name,fn)
    local ok,err=pcall(fn)
    if ok then passed+=1; print("PASS",name) else failed+=1; warn("FAIL",name,err) end
end
local function fixture(skin)
    local now=0
    local r=Resolver.new(function() return now end)
    r:Register("trainee",skin)
    return r,function(t) now=t end
end
test("No item blocks activation",function()
    local r=fixture()
    local ok,why=r:RequestParry("trainee")
    assert(not ok and why=="NOT_OWNED")
end)
test("Basic contact inside window",function()
    local r,time=fixture("Default")
    assert(r:RequestParry("trainee"));time(.799)
    local result,stun=r:ResolveSyntheticContact("trainee",1,"Basic",true)
    assert(result=="PARRY_SUCCESS" and stun==4)
    assert(r.items:GetRemaining("trainee")==90)
end)
test("Exact expiration is outside window",function()
    local r,time=fixture("Default")
    assert(r:RequestParry("trainee"));time(.8)
    assert(r:ResolveSyntheticContact("trainee",1,"Basic",true)=="HIT")
    assert(math.abs(r.items:GetRemaining("trainee")-59.2)<1e-8)
end)
test("Lunge inside window",function()
    local r,time=fixture("Default")
    assert(r:RequestParry("trainee"));time(.3)
    assert(r:ResolveSyntheticContact("trainee",1,"Lunge",true)=="PARRY_SUCCESS")
end)
for _,kind in ipairs({"Projectile","Special","Grab"}) do
    test("Bypass: "..kind,function()
        local r=fixture("Default")
        assert(r:RequestParry("trainee"))
        assert(r:ResolveSyntheticContact("trainee",1,kind,true)~="PARRY_SUCCESS")
        assert(r.items:GetRemaining("trainee")==60)
    end)
end
for _,state in ipairs({"Vaulting","Repairing","Unhooking","Stunned","Grabbed","Downed"}) do
    test("Action lock: "..state,function()
        local r=fixture("Default")
        assert(r:SetAction("trainee",state))
        local ok,why=r:RequestParry("trainee")
        assert(not ok and why=="ACTION_LOCK")
    end)
end
test("Feint does not consume success",function()
    local r,time=fixture("Default")
    assert(r:RequestParry("trainee"))
    assert(r:ResolveSyntheticContact("trainee",1,"Lunge",false)=="NO_CONTACT")
    time(.8)
    assert(r.items:GetRemaining("trainee")<60)
end)
test("Duplicate event ignored",function()
    local r=fixture("Default")
    assert(r:RequestParry("trainee"))
    assert(r:ResolveSyntheticContact("trainee",1,"Basic",true)=="PARRY_SUCCESS")
    assert(r:ResolveSyntheticContact("trainee",1,"Basic",true)=="DUPLICATE")
end)
test("Duplicate activation rejected",function()
    local r=fixture("Default")
    assert(r:RequestParry("trainee"))
    assert(not r:RequestParry("trainee"))
end)
test("Cooldown exact boundary",function()
    local r,time=fixture("Default")
    assert(r:RequestParry("trainee"))
    time(59.99);assert(not r:RequestParry("trainee"))
    time(60);assert(r:RequestParry("trainee"))
end)
test("Interruption invalidates parry",function()
    local r=fixture("Default")
    assert(r:RequestParry("trainee"))
    assert(r:SetAction("trainee","Downed"))
    assert(r:ResolveSyntheticContact("trainee",1,"Basic",true)=="HIT")
end)
test("Respawn preserves cooldown",function()
    local r,time=fixture("Default")
    assert(r:RequestParry("trainee"))
    time(1);assert(r:Respawn("trainee"))
    assert(r.actors.trainee:GetState()=="Idle")
    assert(r.items:GetRemaining("trainee")==59)
end)
test("Remove cleans state",function()
    local r=fixture("Default")
    r:Remove("trainee")
    assert(r.actors.trainee==nil and r.items.users.trainee==nil and r.attacks.trainee==nil)
end)
for _,skin in ipairs({"Blood Shield","Fih","Enten","Feedbacker","Parry Sickle","Stopwatch"}) do
    test("Skin: "..skin,function()
        local r=fixture(skin)
        assert(r:RequestParry("trainee"))
        assert(r:ResolveSyntheticContact("trainee",1,"Basic",true)=="PARRY_SUCCESS")
    end)
end
print(("PARRY TRAINING TESTS: %d passed, %d failed"):format(passed,failed))
assert(failed==0,"Training tests failed")
